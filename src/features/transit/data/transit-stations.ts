/**
 * Searches the registered transit registry for real Metro stations, Bus Terminals,
 * and Bus Stops within the specified radius of a given coordinate.
 */
export function findNearbyRegisteredTransitStops(
  origin: Coordinate,
  metroRadiusMeters: number = 4500,
  busRadiusMeters: number = 3800,
): Place[] {
  const matches: Place[] = [];

  for (const stop of REGISTERED_TRANSIT_STOPS) {
    const dist = Math.round(distanceMeters(origin, stop.coordinate));
    const maxRadius = stop.type === 'metro' ? metroRadiusMeters : busRadiusMeters;

    if (dist <= maxRadius) {
      matches.push({
        id: `reg-${stop.id}`,
        name: stop.name,
        category: 'transport',
        coordinate: stop.coordinate,
        openAtJourneyTime: true,
        openTime: stop.openTime,
        closeTime: stop.closeTime,
        is24_7: stop.is24_7,
        distanceFromRouteMeters: dist,
        dataSource: 'provider',
      });
    }
  }

  // Sort strictly by distance to origin (nearest first)
  matches.sort((a, b) => (a.distanceFromRouteMeters ?? 0) - (b.distanceFromRouteMeters ?? 0));
  return matches;
}
